"""
Lit copies of the pack shaders, for the things lying on the floor waiting to be picked up (user, 2026-09-17).

    python tools/gen_lit_pickup_vmats.py

A pickup in an unlit corner of the dungeon is invisible, so the pickups get their own materials: the same toon shader
with a raised AMBIENT FLOOR (heden_toon's `g_flAmbientFloor`, the minimum light on the shadow side), and nothing else
touched, so they still read as the same object in the same world.

    Assets/Shaders/PickupLit/<name>.vmat   ambient floor 0.30   potions, weapons on the floor and in the racks
    Assets/Shaders/ScrollFull.vmat         ambient floor 1.00   the enchantment scroll (fully lit; the user's call)
    Assets/Shaders/RealmsScrollSpell.vmat  ambient floor 1.00   the gold-sealed spell scroll (hand-written, patched here)

The sources are every visible material the pickups' models remap to (`grep "to = " Assets/PlayerWeapons/*.vmdl` plus
the potion and scroll props); outline materials are NOT copied, the outline is unlit anyway. The runtime list of names
lives in Code/Rendering/PickupLit.cs and must match SOURCES here.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
SHADERS = os.path.join(ROOT, "Assets", "Shaders")
OUT = os.path.join(SHADERS, "PickupLit")

# every visible (non-outline) material a pickup's model uses
SOURCES = [
    "DungeonShader",            # the potions, and the DungeonPack swords
    "RealmsShader",             # the Dungeon Realms weapons and the scroll paper
    "FantasyKingdomShader",
    "DarkFantasyShader",
    "DarkFortressShader01B",
    "BladeShader",              # the starting sword's slots (a skin can share them)
    "IronShader",
    "WoodHandleShader",
    "BrassShader",
    "GemShader",                # the starting staff's gem
    "StaffShader",
    "StaffGem",
]

PICKUP_FLOOR = 0.30
FULL_FLOOR = 1.00


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def set_floor(text, floor):
    out, n = re.subn(r'(g_flAmbientFloor\s+")[^"]*(")', lambda m: f'{m.group(1)}{floor:.3f}{m.group(2)}', text)
    if n != 1:
        raise RuntimeError(f"expected exactly one g_flAmbientFloor, found {n}")
    return out


def write(path, text, note):
    body = text
    if body.startswith("//"):
        body = body.split("\n", 1)[1].lstrip("\n")
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"// {note}\n// GENERATED by tools/gen_lit_pickup_vmats.py - do not edit by hand.\n\n{body}")


def main():
    os.makedirs(OUT, exist_ok=True)
    written = []
    for name in SOURCES:
        src = os.path.join(SHADERS, name + ".vmat")
        if not os.path.exists(src):
            print(f"[lit] SKIP {name}: no {os.path.relpath(src, ROOT)}")
            continue
        text = set_floor(read(src), PICKUP_FLOOR)
        dst = os.path.join(OUT, name + ".vmat")
        write(dst, text, f"{name} for a pickup lying in the dungeon: ambient floor {PICKUP_FLOOR:.2f} so it is visible in an unlit corner.")
        written.append(os.path.relpath(dst, ROOT))

    # the enchantment scroll's paper, fully lit: RealmsShader as the scroll model uses it (atlas 01_a)
    scroll = set_floor(read(os.path.join(SHADERS, "RealmsShader.vmat")), FULL_FLOOR)
    dst = os.path.join(SHADERS, "ScrollFull.vmat")
    write(dst, scroll, f"The sealed enchantment scroll (ScrollPickup): RealmsShader, ambient floor {FULL_FLOOR:.2f} - fully lit wherever it lies.")
    written.append(os.path.relpath(dst, ROOT))

    # the gold spell scroll is hand-written (its own atlas): only its floor is patched
    spell_path = os.path.join(SHADERS, "RealmsScrollSpell.vmat")
    spell = read(spell_path)
    with open(spell_path, "w", encoding="utf-8") as f:
        f.write(set_floor(spell, FULL_FLOOR))
    written.append(os.path.relpath(spell_path, ROOT))

    print(f"[lit] wrote {len(written)} materials:")
    for w in written:
        print("   ", w)


main()
