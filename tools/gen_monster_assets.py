def write_vmat(name, body, force):
    path = os.path.join(SHADER_DIR, name + ".vmat")
    if os.path.exists(path) and not force:
        return False
    with open(path, "w", newline="\n") as f:
        f.write(body)
    return True


def mesh_node(filename, names, node_name):
    ex = "".join('\t\t\t\t\t\t\t\t"%s",\n' % n for n in names)
    return f'''					{{
						_class = "RenderMeshFile"
						name = "{node_name}"
						filename = "{filename}"
						import_translation = [ 0.0, 0.0, 0.0 ]
						import_rotation = [ 0.0, 0.0, 0.0 ]
						import_scale = 1.0
						align_origin_x_type = "None"
						align_origin_y_type = "None"
						align_origin_z_type = "None"
						parent_bone = ""
						import_filter =
						{{
							exclude_by_default = true
							exception_list =
							[
{ex}							]
						}}
					}},
'''


def anim_node(name, source, looping):
    return f'''					{{
						_class = "AnimFile"
						name = "{name}"
						activity_name = ""
						activity_weight = 1
						weight_list_name = ""
						fade_in_time = 0.2
						fade_out_time = 0.2
						looping = {"true" if looping else "false"}
						delta = false
						worldSpace = false
						hidden = false
						anim_markup_ordered = false
						disable_compression = false
						disable_interpolation = false
						enable_scale = false
						source_filename = "{source}"
						start_frame = -1
						end_frame = -1
						framerate = -1.0
						take = 0
						reverse = false
					}},
'''


def markup(bone):
    return f'''					{{
						_class = "BoneMarkup"
						target_bone = "{bone}"
						ignore_Translation = false
						ignore_rotation = false
						do_not_discard = true
					}},
'''


def write_vmdl(kind, manifest):
    # Measure the FBX the compiler will actually read, never Blender's numbers: the export writes geometry in
    # metres under a flat 100x node scale (and Blender's own bound_box is the posed box, not the bind pose).
    body_size = fbx_bounds.mesh_world_sizes(kind["fbx"])[manifest["body_mesh"]]
    scale = kind["size"] / max(body_size)
    remaps = "".join(f'''							{{
								from = "{n.lower()}.vmat"
								to = "shaders/{n.lower()}.vmat"
							}},
''' for n in list(manifest["materials"]) + [monster_kinds.OUTLINE_MATERIAL])
    # the ragdoll capsules (gen_monster_ragdoll.py); every monster ragdolls, none plays its death clip
    physics = f'''			{{
				_class = "PhysicsShapeList"
				children =
				[
					{{
						_class = "Prefab"
						target_file = "{kind["physics_rel"]}"
					}},
				]
			}},
''' if os.path.exists(kind["physics_prefab"]) else ""
    if not physics:
        print("  no ragdoll at %s - PhysicsShapeList omitted (run tools/gen_monster_ragdoll.py)" % kind["physics_rel"])
    animgraph = kind["animgraph_rel"] if os.path.exists(kind["animgraph"]) else ""
    if not animgraph:
        print("  no animgraph at %s - the vmdl gets none (run tools/gen_monster_animgraph.py)" % kind["animgraph_rel"])
    meshes = mesh_node(kind["fbx_rel"], [manifest["body_mesh"], manifest["outline_mesh"]], "body")
    anims = "".join(anim_node(c["name"], kind["clip_rel"] + c["name"] + ".fbx", c["name"] in LOOPING)
                    for c in manifest["clips"])
    markups = "".join(markup(b) for b in manifest["bones"])
    out = f'''<!-- kv3 encoding:text:version{{e21c7f3c-8a33-41c5-9977-a76d3a32aa0d}} format:modeldoc30:version{{8c2d7a91-9c42-4bf0-883a-5a3b1762d4f1}} -->
{{
	rootNode =
	{{
		_class = "RootNode"
		children =
		[
			{{
				_class = "MaterialGroupList"
				children =
				[
					{{
						_class = "DefaultMaterialGroup"
						remaps =
						[
{remaps}						]
						use_global_default = false
						global_default_material = "materials/default.vmat"
					}},
				]
			}},
{physics}			{{
				_class = "RenderMeshList"
				children =
				[
{meshes}				]
			}},
			{{
				_class = "AnimationList"
				children =
				[
{anims}				]
				default_root_bone_name = "{manifest["root_bone"]}"
			}},
			{{
				_class = "BoneMarkupList"
				children =
				[
{markups}				]
			}},
			{{
				_class = "ModelModifierList"
				children =
				[
					{{
						_class = "ModelModifier_ScaleAndMirror"
						scale = {scale:.6f}
						mirror_x = false
						mirror_y = false
						mirror_z = false
						flip_bone_forward = false
						swap_left_and_right_bones = false
					}},
				]
			}},
		]
		model_archetype = ""
		primary_associated_entity = ""
		anim_graph_name = "{animgraph}"
		base_model_name = ""
	}}
}}
'''
    with open(kind["vmdl"], "w", newline="\n") as f:
        f.write(out)
    size = [round(v * scale, 1) for v in body_size]
    # what the model came out as, for gen_monster_prefabs.py: FBX axes are (x, y = UP, z = depth), so the
    # in-game height is size[1]. `units_per_bu` turns a Blender-unit measurement (the clip reaches and stance
    # speeds) into game units in one step.
    with open(kind["model_json"], "w", newline="\n") as f:
        json.dump(dict(kind=kind["name"], scale=scale, fbx_size=list(body_size),
                       width=size[0], height=size[1], depth=size[2], units_per_bu=scale * 100.0,
                       root_bone=manifest["root_bone"], bones=len(manifest["bones"]),
                       clips=[c["name"] for c in manifest["clips"]]), f, indent=2)
    print("wrote %s: %d clips (%d looping), %d bones, fbx %s, scale %.5f -> %s units" % (
        os.path.relpath(kind["vmdl"], ROOT), len(manifest["clips"]),
        sum(c["name"] in LOOPING for c in manifest["clips"]), len(manifest["bones"]),
        [round(v) for v in body_size], scale, size))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--force-vmats", action="store_true", help="overwrite vmats that already exist (loses hand tuning)")
    monster_kinds.add_kind_arg(ap)
    args = ap.parse_args()
    write_white_png(TEXTURE)
    written = write_vmat(monster_kinds.OUTLINE_MATERIAL, OUTLINE_VMAT, args.force_vmats)
    made = int(written)
    for name in monster_kinds.selected(args.kind):
        kind = monster_kinds.kind(name)
        if not os.path.exists(kind["manifest"]):
            raise SystemExit("no manifest at %s - run tools/prep_monster.py --kind %s first" % (kind["manifest"], name))
        with open(kind["manifest"]) as f:
            manifest = json.load(f)
        for mat, info in manifest["materials"].items():
            if write_vmat(mat, surface_vmat(info["linear"]), args.force_vmats):
                made += 1
                print("  %-26s tint %s (pack slot %s)" % (mat + ".vmat", [round(c, 4) for c in info["linear"]], info["pack_slot"]))
        write_vmdl(kind, manifest)
    print("%d vmats written" % made)


if __name__ == "__main__":
    main()
