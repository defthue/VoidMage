"""Write the s&box side of the Quaternius monsters (tools/monster_kinds.py): one vmat per material slot,
the shared outline vmat, the white texture those flat colours ride on, and one vmdl per monster listing
every clip tools/prep_monster.py exported.

    python tools/gen_monster_assets.py [--kind bat] [--force-vmats]

Reads tools/out/monsters/<kind>.json (written by prep_monster.py), so this is the cheap half: retuning a
monster's `size` in monster_kinds.py and rerunning this is enough, no Blender.

Colour: these packs carry no textures at all, just a flat base colour per material. Each slot therefore gets
heden_toon.shader over an 8x8 white texture with the pack's colour in `g_vTextureTint` — the albedo sampler
reads sRGB, so a white texel is 1.0 linear and the tint IS the albedo, exactly the LINEAR value Blender had.
The bat and the dragon really are near-black that way (Quaternius authored them at 0.02-0.05); brighten the
tint in the material editor rather than here. Existing vmats are left alone unless --force-vmats, so hand
tuning survives a rerun; the vmdls are always rewritten.
"""
import argparse, json, os, struct, sys, zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import fbx_bounds  # noqa: E402
import monster_kinds  # noqa: E402

TEXTURE = os.path.join(ROOT, "Assets", "Textures", "Monsters", "flat_white.png")
SHADER_DIR = os.path.join(ROOT, "Assets", "Shaders")
# clips that should loop: the pack's names, one regex list for all eight monsters
LOOPING = ("idle", "flying", "walk", "run")


def write_white_png(path, size=8):
    """A solid white 8x8 texture. The flat colours live in each vmat's tint; this is just the 1.0 it multiplies."""
    if os.path.exists(path):
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    raw = b"".join(b"\x00" + b"\xff\xff\xff" * size for _ in range(size))

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    png = (b"\x89PNG\r\n\x1a\n"
           + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0))
           + chunk(b"IDAT", zlib.compress(raw, 9))
           + chunk(b"IEND", b""))
    with open(path, "wb") as f:
        f.write(png)
    print("wrote", path)


